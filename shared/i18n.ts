/** The doctor-entered profile in the interface language (prompts use describeProfile in English). */
export function profileText(lang: Lang, p: { level: string; side: string; stage: string; cause: string; restrictions: string; limbs?: Limb[] }) {
  const side = t(lang, p.side === "right" ? "right" : "left");
  const limbs = limbsOf(p as Parameters<typeof limbsOf>[0]);
  if (!limbs.length) return { en: `No amputation (tester), ${side} leg exercises`, id: `Tanpa amputasi (penguji), kaki ${side} berlatih`, zh: `无截肢（测试者），${side}腿练习` }[lang];
  const parts = [limbs.map((l) => limbLine(lang, l)).join(" + "), words[`${p.stage as "prosthetic" | "pre_prosthetic"}${limbs.some((l) => l.site === "lower") ? "" : "_arm"}` as const][lang]];
  if (p.cause !== "unknown") parts.push(words[p.cause as keyof typeof words][lang]);
  const text = parts.join(" · ") + (p.restrictions ? ` · ${p.restrictions}` : "");
  return text.charAt(0).toUpperCase() + text.slice(1);
}
