/** The doctor-entered profile in the interface language (prompts use describeProfile in English). */
export function profileText(lang: Lang, p: { level: string; side: string; stage: string; cause: string; restrictions: string }) {
  const side = t(lang, p.side === "right" ? "right" : "left");
  if (p.level === "none") return { en: `No amputation (tester), ${side} leg exercises`, id: `Tanpa amputasi (penguji), kaki ${side} berlatih`, zh: `无截肢（测试者），${side}腿练习` }[lang];
  const level = words[p.level as "below_knee" | "above_knee"][lang];
  const where = { en: `${level}, ${side} leg`, id: `${level}, kaki ${side}`, zh: `${side}腿${level}` }[lang];
  const parts = [where, words[p.stage as "prosthetic" | "pre_prosthetic"][lang]];
  if (p.cause !== "unknown") parts.push(words[p.cause as keyof typeof words][lang]);
  const text = parts.join(" · ") + (p.restrictions ? ` · ${p.restrictions}` : "");
  return text.charAt(0).toUpperCase() + text.slice(1);
}
